/**
 * Token CSS Generator Script
 * 
 * Run this script to regenerate tokens.css from figma-tokens.json
 * Usage: npm run generate-tokens
 * 
 * Note: This is a utility script. The tokens.css file can also be manually maintained.
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { generateThemeCSS } from './generate-css.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const outputPath = join(__dirname, 'tokens.css');

try {
	const brandACSS = generateThemeCSS('brandA');
	const brandBCSS = generateThemeCSS('brandB');
	
	const css = `/**
 * Design Token CSS Variables
 * 
 * This file is generated from design tokens and provides CSS custom properties
 * for theme switching. The variables are set based on the data-theme attribute.
 * 
 * This file is automatically generated. To regenerate, run: npm run generate-tokens
 * 
 * Last generated: ${new Date().toISOString()}
 */

/* Brand A Theme (Default) */
[data-theme="brandA"],
:root {
${brandACSS.split('\n').slice(1).join('\n')}
}

/* Brand B Theme */
[data-theme="brandB"] {
${brandBCSS.split('\n').slice(1).join('\n')}
}
`;

	writeFileSync(outputPath, css, 'utf-8');
	console.log('✅ Successfully generated tokens.css');
	console.log(`📁 Output: ${outputPath}`);
} catch (error) {
	console.error('❌ Error generating tokens.css:', error);
	process.exit(1);
}
